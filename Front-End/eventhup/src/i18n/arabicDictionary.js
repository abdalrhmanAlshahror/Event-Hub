const months = {
    January: "يناير", February: "فبراير", March: "مارس", April: "أبريل",
    May: "مايو", June: "يونيو", July: "يوليو", August: "أغسطس",
    September: "سبتمبر", October: "أكتوبر", November: "نوفمبر", December: "ديسمبر",
};

const units = {
    second: "ثانية", minute: "دقيقة", hour: "ساعة", day: "يوم",
    week: "أسبوع", month: "شهر", year: "سنة",
};

export const patterns = [
    // June 15, 2026  ←  15 يونيو 2026
    [
        new RegExp(`^(${Object.keys(months).join("|")}) (\\d{1,2}), (\\d{4})$`),
        (month, day, year) => `${day} ${months[month]} ${year}`,
    ],
    // 5 minutes ago  ←  منذ 5 دقيقة
    [
        /^(\d+) (second|minute|hour|day|week|month|year)s? ago$/,
        (n, unit) => `منذ ${n} ${units[unit]}`,
    ],
    [/^just now$/i, () => "الآن"],
];